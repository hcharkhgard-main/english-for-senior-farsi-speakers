// Writes ai-proxy/personas.json: the allow-list of conversations the optional live AI partner
// may play, with the fixed role and scene text for each one.
//
// The proxy builds the model's instructions from this file only. A visitor's browser sends the
// id of a conversation, never the role text, so the service cannot be turned into a
// general-purpose chatbot, and conversations that are safety-critical, scripted, or that ask
// the learner for personal details are simply not in the list (see liveBlock in
// src/js/ai-prompt.js).
//
// Run it again whenever a file content/roleplays*.json is added or changed:
//     npm run personas          (or: node tools/make-personas.mjs)
// and then deploy the proxy again. `npm test` fails while the file is missing or out of date.
//     node tools/make-personas.mjs --check     exits 1 if the file is missing or out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { liveBlock, personaOf } from '../src/js/ai-prompt.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PERSONAS_FILE = path.join(ROOT, 'ai-proxy', 'personas.json');

export function buildPersonas(contentDir = path.join(ROOT, 'content')) {
  const files = fs.readdirSync(contentDir).filter((f) => /^roleplays.*\.json$/.test(f)).sort();
  const all = files.flatMap((f) => JSON.parse(fs.readFileSync(path.join(contentDir, f), 'utf8')).roleplays || []);
  const personas = {}, excluded = {};
  for (const R of [...all].sort((a, b) => String(a.id).localeCompare(String(b.id)))) {
    if (!/^[a-z0-9][a-z0-9-]{0,39}$/.test(String(R.id))) throw new Error(`conversation id "${R.id}" must be lower-case letters, digits and hyphens (at most 40)`);
    if (personas[R.id] || excluded[R.id]) throw new Error(`conversation id "${R.id}" is used twice`);
    const why = liveBlock(R);
    if (why) excluded[R.id] = why; else personas[R.id] = personaOf(R);
  }
  return {
    note: 'Generated by tools/make-personas.mjs from content/roleplays*.json. Do not edit by hand: run "npm run personas" after changing a conversation, then deploy the proxy again.',
    personas,
    excluded,
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = JSON.stringify(buildPersonas(), null, 2) + '\n';
  const current = fs.existsSync(PERSONAS_FILE) ? fs.readFileSync(PERSONAS_FILE, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current === text) console.log('ai-proxy/personas.json is up to date.');
    else { console.error(current === null ? 'ai-proxy/personas.json is missing.' : 'ai-proxy/personas.json is out of date.', 'Run: npm run personas'); process.exit(1); }
  } else {
    if (current !== text) fs.writeFileSync(PERSONAS_FILE, text);
    const out = JSON.parse(text);
    console.log(`${current === text ? 'Unchanged' : 'Wrote'} ai-proxy/personas.json — ${Object.keys(out.personas).length} conversations open to the live partner, ${Object.keys(out.excluded).length} closed:`);
    for (const [id, why] of Object.entries(out.excluded)) console.log(`  closed  ${id}  (${why})`);
    for (const id of Object.keys(out.personas)) console.log(`  open    ${id}`);
  }
}
